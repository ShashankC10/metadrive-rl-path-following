"""Build results tables and plots from saved evaluation CSVs and validation logs.

    python scripts/make_report.py   ->  docs/results.md, docs/figures/*.png
"""
import glob
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from path_following.metrics import summarize, bootstrap_ci

EVAL, FIG = Path("outputs/eval"), Path("docs/figures")
FIG.mkdir(parents=True, exist_ok=True)


def md_table(df):
    head = "| " + " | ".join(df.columns) + " |\n| " + " | ".join("---" for _ in df.columns) + " |\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False))


def load(prefix, split):
    return {Path(f).stem.replace(f"_{split}", ""): pd.read_csv(f)
            for f in sorted(glob.glob(str(EVAL / f"{prefix}*_{split}.csv")))}


def pct(r, k): return f"{100*r[k+'_rate']:.1f} [{100*r[k+'_lo']:.1f}, {100*r[k+'_hi']:.1f}]"
def ci(r, k, f="{:.3f}"): return f"{f.format(r[k])} [{f.format(r[k+'_lo'])}, {f.format(r[k+'_hi'])}]"


def row(name, df):
    r = summarize(df)
    return {"controller": name, "n": r["n_episodes"], "success % [95% CI]": pct(r, "success"),
            "off-road %": pct(r, "off_road"), "crash/stall/timeout": f"{int(df.crash.sum())}/{int(df.stall.sum())}/{int(df.timeout.sum())}",
            "mean |lat| m [CI]": ci(r, "mean_abs_lat"), "RMS lat m [CI]": ci(r, "rms_lat"),
            "time on success s [CI]": ci(r, "time_success_s", "{:.1f}") + f" (n={r['n_success']})",
            "progress on failures": f"{r['progress_failed']:.2f}" if not np.isnan(r["progress_failed"]) else "-",
            "mean speed m/s": f"{r['mean_speed']:.2f}"}


def group_tables(split):
    base, ppo, abl = load("baseline", split), load("ppo_s", split), load("abl_s", split)
    out = []
    if base:
        out.append(row("pure pursuit", base["baseline"]))
    for name, d in ppo.items():
        out.append(row(name, d))
    for name, d in abl.items():
        out.append(row(name + " (no lookahead)", d))
    return pd.DataFrame(out)


def seed_variability(prefix, split, label):
    """Across-seed mean and range of per-seed metrics (variability over training seeds)."""
    d = load(prefix, split)
    if not d:
        return ""
    per = pd.DataFrame({k: dict(success=v.success.mean(), off_road=v.off_road.mean(), rms_lat=v.rms_lat.mean(),
                                mean_abs_lat=v.mean_abs_lat.mean(), time=v.time_s[v.success].mean()) for k, v in d.items()}).T
    s = f"- **{label}** over {len(per)} training seeds: success {100*per.success.mean():.1f}% "
    s += f"(seed range {100*per.success.min():.1f}-{100*per.success.max():.1f}%), RMS lateral {per.rms_lat.mean():.3f} m "
    s += f"(range {per.rms_lat.min():.3f}-{per.rms_lat.max():.3f}), time on success {per.time.mean():.1f} s.\n"
    return s


def learning_curves():
    fig, ax = plt.subplots(1, 2, figsize=(11, 3.6))
    for prefix, colour, label in (("ppo_s", "tab:blue", "PPO"), ("abl_s", "tab:orange", "PPO, no lookahead")):
        for i, f in enumerate(sorted(glob.glob(f"checkpoints/{prefix}*/val_log.jsonl"))):
            d = pd.DataFrame([json.loads(l) for l in open(f)])
            ax[0].plot(d.step, d.val_success, color=colour, alpha=0.8, label=label if i == 0 else None)
            ax[1].plot(d.step, d.val_mean_abs_lat, color=colour, alpha=0.8)
    ax[0].set(xlabel="training steps", ylabel="validation success rate", title="Validation success (20 layouts)")
    ax[1].set(xlabel="training steps", ylabel="mean |lateral error| (m)", title="Validation tracking error")
    ax[0].legend(); fig.tight_layout(); fig.savefig(FIG / "learning_curves.png", dpi=130)


def comparison_plot(split):
    base, ppo = load("baseline", split), load("ppo_s", split)
    if not base or not ppo:
        return
    names = ["pure pursuit"] + list(ppo)
    dfs = [base["baseline"]] + list(ppo.values())
    fig, ax = plt.subplots(1, 3, figsize=(12, 3.4))
    for k, (col, title) in enumerate((("success", "success rate"), ("mean_abs_lat", "mean |lateral error| (m)"), ("mean_speed", "mean speed (m/s)"))):
        m = [d[col].mean() for d in dfs]; ci_ = [bootstrap_ci(d[col]) for d in dfs]
        ax[k].bar(names, m, yerr=[[a - c[0] for a, c in zip(m, ci_)], [c[1] - a for a, c in zip(m, ci_)]], color=["gray"] + ["tab:blue"] * len(ppo), capsize=3)
        ax[k].set_title(title); ax[k].tick_params(axis="x", rotation=30)
    fig.tight_layout(); fig.savefig(FIG / f"comparison_{split}.png", dpi=130)


def main():
    lines = ["# Results\n", "Generated by `scripts/make_report.py` from `outputs/eval/*.csv`. Intervals: Wilson 95% for rates; "
             "percentile bootstrap over layouts for means. PPO checkpoints are the best-validation-score checkpoint "
             "of each training seed; test was evaluated once.\n"]
    for split, title in (("val", "Validation layouts (used for tuning/checkpoint selection)"), ("test", "Held-out test layouts (final)")):
        t = group_tables(split)
        if len(t):
            lines += [f"## {title}\n", md_table(t), "\n"]
            lines += [seed_variability("ppo_s", split, "PPO"), seed_variability("abl_s", split, "PPO without lookahead"), "\n"]
        comparison_plot(split)
    learning_curves()
    Path("docs/results.md").write_text("\n".join(lines))
    print("wrote docs/results.md")


if __name__ == "__main__":
    main()
